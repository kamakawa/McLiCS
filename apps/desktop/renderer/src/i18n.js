export function normalizeLang(lang) {
  if (!lang) return "en";
  const raw = String(lang).trim();
  const canonical = LANG_ALIASES[raw] || LANG_ALIASES[raw.toLowerCase()] || raw;
  return LANG_OPTIONS.some((opt) => opt.value === canonical) ? canonical : "en";
}

