export function translate(lang, key, vars = {}) {
  const base = dict[normalizeLang(lang)] || dict.en;
  const template = base[key] ?? dict.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}