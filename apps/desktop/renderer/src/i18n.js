export function translate(lang, key, vars = {}) {
  const base = dict[normalizeLang(lang)] || dict.en;
  const value = base[key] ?? dict.en[key] ?? key;

  if (typeof value === "string") {
    return value.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
  }

  return value;
}